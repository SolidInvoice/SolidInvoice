namespace SolidInvoice\CoreBundle\Listener;

use InvalidArgumentException;
use Symfony\Component\EventDispatcher\EventSubscriberInterface;
use Symfony\Component\HttpKernel\Event\ExceptionEvent;
use Symfony\Component\HttpKernel\Exception\NotFoundHttpException;
use Symfony\Component\HttpKernel\KernelEvents;

/**
 * @see \SolidInvoice\CoreBundle\Tests\Listener\LiveComponentExceptionListenerTest
 */
final class LiveComponentExceptionListener implements EventSubscriberInterface
{
    public static function getSubscribedEvents(): array
    {
        return [
            KernelEvents::EXCEPTION => 'onKernelException',
        ];
    }

    public function onKernelException(ExceptionEvent $event): void
    {
        $exception = $event->getThrowable();

        if (! $exception instanceof InvalidArgumentException) {
            return;
        }

        if ($event->getRequest()->attributes->get('_route') !== 'ux_live_component') {
            return;
        }

        $event->setThrowable(new NotFoundHttpException($exception->getMessage(), $exception));
    }
}
